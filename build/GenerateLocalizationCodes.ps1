Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Escape-XmlDocumentation([string]$value)
{
    return $value
        .Replace('&', '&amp;')
        .Replace('<', '&lt;')
        .Replace('>', '&gt;')
        .Replace("`r", '&#13;')
        .Replace("`n", '&#10;')
}

[xml]$resourceXml = Get-Content -LiteralPath $ResourcePath
$entries = @(
    $resourceXml.root.data |
        Where-Object { $_.name } |
        ForEach-Object {
            $valueNode = $_.SelectSingleNode('value')
            $commentNode = $_.SelectSingleNode('comment')
            [PSCustomObject]@{
                Name = $_.name
                Value = if ($null -eq $valueNode) { '' } else { [string]$valueNode.InnerText }
                Comment = if ($null -eq $commentNode) { '' } else { [string]$commentNode.InnerText }
            }
        } |
        Sort-Object Name
)

