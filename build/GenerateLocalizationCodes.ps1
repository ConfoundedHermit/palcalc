    [string]$ResourcePath = (Join-Path $PSScriptRoot '..\PalCalc.UI\Localization\LocalizationCodes.resx'),
    [string]$OutputPath = (Join-Path $PSScriptRoot '..\PalCalc.UI\Localization\LocalizationCodes.Designer.cs')
